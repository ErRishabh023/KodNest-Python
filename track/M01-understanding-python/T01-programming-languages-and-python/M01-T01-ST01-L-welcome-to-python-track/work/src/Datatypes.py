#init
a = 10
print(type(a),a)

#float
b=34.5 
print(type(b),b)

#str
c="python" 
print(type(c),c)

#bool
d=True # false
print(type(d),d)

#complex
e=3+4j #4j is the imaginary part
print(type(e),e)

#list
f=[1,2,3,4,5]
print(type(f),f)

#tuple
g=(1,2,3,4,5)
print(type(g),g)

#set
h={1,2,3,4,5}
print(type(h),h)

#dict
i={1:"one",2:"two",3:"three",4:"four",5:"five"}
print(type(i),i)

#None
j=None
print(type(j),j)

